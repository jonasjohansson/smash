const segmentSummary = (slug: string): SegmentSummary => {
  const s = seedSegments.find((x) => x.slug === slug);
  if (!s) throw new Error(`seed: unknown segment "${slug}"`);
  return { _id: s._id, title: s.title, slug: s.slug, intro: s.intro };
};

/* ------------------------------------------------------------------ *
 * Case studies — stand-in: Jonas Johansson's portfolio projects.
 *
 * `portfolio.json` is generated by `scripts/import-portfolio.mjs` from the
 * jonasjohansson.se repo, so the templates can be judged against real images
 * and real copy until SMASH's own case studies exist.
 * ------------------------------------------------------------------ */

interface PortfolioProject {
  slug: string;
  title: string;
  date: string;
  tags: string[];
  texts: string[];
  images: { src: string; alt: string; aspect: MediaAspect }[];
}

/** Portfolio tags → the four SMASH segments. */
const TAG_SEGMENTS: Record<string, string> = {
  mapping: 'projection-mapping',
  light: 'immersive-environments',
  stage: 'immersive-environments',
  av: 'immersive-environments',
  community: 'interactive-installations',
  'mixed reality': 'interactive-installations',
  design: 'digital-experiences',
};

const NARRATIVE_HEADINGS = ['The idea', 'The context', 'The audience experience', 'What changed'];

function fromPortfolio(p: PortfolioProject, i: number): CaseStudy {
  const img = (n: number): Media | null => {
    const x = p.images[n];
    return x ? { ...media(x.alt, x.aspect), _key: `${p.slug}-${n}`, src: x.src } : null;
  };
  const slugs = [...new Set(p.tags.map((t) => TAG_SEGMENTS[t]).filter(Boolean))];
  const section = (n: number) => ({
    heading: NARRATIVE_HEADINGS[n],
    // The last beat carries every remaining paragraph.
    body: pt(...(n === 3 ? p.texts.slice(3) : p.texts.slice(n, n + 1))),
    media: [img(n + 1)].filter((m): m is Media => m !== null),
  });
  return {
    _id: `case.${p.slug}`,
    title: p.title,
    slug: p.slug,
    client: 'Jonas Johansson',
    year: new Date(p.date).getFullYear(),
    featured: i < 4,
    order: i + 1,
    segments: (slugs.length ? slugs : ['interactive-installations']).map(segmentSummary),
    heroMedia: img(0)!,
    idea: section(0),
    context: section(1),
    experience: section(2),
    transformation: section(3),
    gallery: p.images.slice(5).map((_, n) => img(n + 5)!),
    credits: [{ _key: 'c1', role: 'Design & direction', name: 'Jonas Johansson' }],
  };
}

export const seedCaseStudies: CaseStudy[] = (portfolio as PortfolioProject[]).map(fromPortfolio);

